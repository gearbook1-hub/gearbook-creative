// Builds the sound kit from public/pieces/sounds/sources.json:
//   npm run sound:prep
// Downloads each source once into .cache/sounds (Kenney packs, Freesound HQ previews, after
// checking the Freesound page still says CC0), then for every file: mono, 48 kHz (soxr), leading
// silence trimmed to the first transient, rumble under 120 Hz cut, cut to the slot's maxLen,
// faded in 2 ms and out 15 ms so it starts and ends on zero, spikes rounded to the slot's crest
// over its loudest 400 ms, and peaked at -1 dBTP. Each file's loudness goes into manifest.json so
// the mixer can set every hit to its slot's level.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { KIT, RATE, duration, ff, loudness } from "./sound.mjs";

const CACHE = path.resolve(".cache", "sounds");
// Crest is true peak over the loudest 400 ms, the two numbers the mixer works with. The loudest
// slot gets CREST; a slot set quieter keeps that much more of its spike, because the mixer lifts
// every slot by the same amount and the quiet ones then still peak no higher (2026-10-21). With
// the target at -16 and ceiling -1.5, a ding peaks at -1 before the limiter and anything else at
// most a few dB over, which the mixer's limiter is allowed to take.
const CREST = 15;
const src = JSON.parse(fs.readFileSync(path.join(KIT, "sources.json"), "utf8"));
const TOP = Math.max(...Object.values(src.slots).map((s) => s.level));
const crest = (slot) => CREST + TOP - slot.level;
const prev = fs.existsSync(path.join(KIT, "manifest.json")) ? JSON.parse(fs.readFileSync(path.join(KIT, "manifest.json"), "utf8")) : {};
fs.mkdirSync(CACHE, { recursive: true });

// True peak and loudest 400 ms in one ffmpeg run, for the crest loop (padded like loudness()).
function peakAndMomentary(file) {
  const t = ff(["-i", file, "-af", `apad=pad_dur=1,ebur128=peak=true:framelog=info`, "-f", "null", "-"]);
  return {
    truePeak: Number(t.match(/True peak:[\s\S]*?Peak:\s+(-?[\d.]+)/)[1]),
    momentary: Math.max(...[...t.matchAll(/ M:\s*(-?[\d.]+)/g)].map((x) => Number(x[1]))),
  };
}

async function download(url, file) {
  if (fs.existsSync(file)) return file;
  const res = await fetch(url, { headers: { "user-agent": "gearbook-creative sound:prep" } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  return file;
}

async function sourceFile(from) {
  if (from.local) return path.resolve(from.local);
  if (from.pack) {
    const pack = src.packs[from.pack];
    const dir = path.join(CACHE, from.pack);
    if (!fs.existsSync(dir)) {
      const zip = await download(pack.zip, path.join(CACHE, `${from.pack}.zip`));
      fs.mkdirSync(dir, { recursive: true });
      // Windows' own tar reads zips; Git Bash's GNU tar (often first on PATH) doesn't.
      execFileSync(process.platform === "win32" ? "C:/Windows/System32/tar.exe" : "unzip", process.platform === "win32" ? ["-xf", zip, "-C", dir] : ["-q", zip, "-d", dir]);
      if (!/CC0|zero/i.test(fs.readFileSync(path.join(dir, "License.txt"), "utf8"))) throw new Error(`${from.pack} is no longer CC0`);
    }
    return path.join(dir, from.file);
  }
  const file = path.join(CACHE, `freesound-${from.freesound}.mp3`);
  if (fs.existsSync(file)) return file;
  const page = `https://freesound.org/people/${from.user}/sounds/${from.freesound}/`;
  const html = await (await fetch(page, { headers: { "user-agent": "Mozilla/5.0" } })).text();
  if (!/publicdomain\/zero|Creative Commons 0/.test(html)) throw new Error(`Freesound ${from.freesound} is not CC0 (${page})`);
  const lq = html.match(new RegExp(`https://cdn\\.freesound\\.org/previews/\\d+/${from.freesound}_\\d+-[hl]q\\.(?:mp3|ogg)`));
  if (!lq) throw new Error(`no preview on ${page}`);
  return download(lq[0].replace(/-lq\.(mp3|ogg)$/, "-hq.mp3"), file);
}

const manifest = {
  about: "Generated by `npm run sound:prep` from sources.json; edit that file instead. `enabled` and each slot's `pick` are kept across runs.",
  enabled: prev.enabled ?? false,
  target: src.target,
  slots: {},
};
for (const [name, slot] of Object.entries(src.slots)) {
  const out = { what: slot.what, level: slot.level, pick: Object.keys(slot.candidates).length ? prev.slots?.[name]?.pick ?? slot.pick : null, candidates: {} };
  for (const [key, cand] of Object.entries(slot.candidates)) {
    const files = [];
    for (const [i, from] of cand.from.entries()) {
      const input = await sourceFile(from);
      const rel = `${name}/${key.toLowerCase()}${i + 1}.wav`;
      fs.mkdirSync(path.join(KIT, name), { recursive: true });
      const tmp = path.join(CACHE, "tmp.wav"), tmp2 = path.join(CACHE, "tmp2.wav");
      // Cut to the first transient (keep 3 ms before it), then to the slot's length.
      ff(["-i", input, "-af", `aformat=channel_layouts=mono,aresample=${RATE}:resampler=soxr,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.003,highpass=f=120,atrim=0:${slot.maxLen}`, "-c:a", "pcm_f32le", tmp]);
      const len = duration(tmp);
      const fade = Math.min(0.015, len / 4);
      const peak = Number(ff(["-i", tmp, "-af", "astats=measure_overall=Peak_level:measure_perchannel=0", "-f", "null", "-"]).match(/Peak level dB:\s*(-?[\d.]+)/)[1]);
      ff(["-i", tmp, "-af", `afade=t=in:d=0.002,afade=t=out:st=${(len - fade).toFixed(4)}:d=${fade.toFixed(4)},volume=${(-1 - peak).toFixed(2)}dB`, "-c:a", "pcm_s16le", path.join(KIT, rel)]);
      let m = loudness(path.join(KIT, rel));
      // A close-miked click can peak 25 dB over its loudest 400 ms: the spike sets the whole reel's
      // level and the click itself stays quiet. Round spikes down to the slot's crest with one pass
      // of an oversampled look-ahead limiter, then peak at -1 dBTP again. The cut that gets there
      // has to be searched for: the first dB of a cut take the click's loudness with them, then
      // past its body crest falls fast (a fixed 16 dB cut left 20 to 26; stacked passes overshot by
      // 3, 2026-10-21). Regula falsi from the untouched file, to within 0.3 dB under the cap. A spike
      // past alimiter's 22.5 dB of reach keeps the rest (tap A's click3 ends 3 dB over).
      const cap = crest(slot);
      if (m.truePeak - m.momentary > cap + 0.3) {
        fs.copyFileSync(path.join(KIT, rel), tmp);
        const at = (cut) => {
          // Starts from -1 dBTP so the limit stays inside alimiter's range (down to -24 dB).
          ff(["-i", tmp, "-af", `volume=${(-1 - m.truePeak).toFixed(2)}dB,aresample=${RATE * 4}:resampler=soxr,alimiter=limit=${Math.pow(10, (-1 - cut) / 20).toFixed(5)}:attack=0.5:release=20:level=false:latency=true,aresample=${RATE}:resampler=soxr`, "-c:a", "pcm_f32le", tmp2]);
          const q = peakAndMomentary(tmp2);
          return { cut, q, over: q.truePeak - q.momentary - cap };
        };
        let lo = { cut: 0, over: m.truePeak - m.momentary - cap }, hi = at(22.5), best = hi;
        let fl = lo.over, fh = hi.over, last = 0;
        for (let i = 0; i < 8 && hi.over <= -0.3; i++) {
          const x = at(lo.cut + (fl * (hi.cut - lo.cut)) / (fl - fh));
          // Illinois: an end kept twice in a row counts half, so the search can't stall on it.
          if (x.over > 0) { lo = x; fl = x.over; if (last < 0) fh /= 2; last = -1; }
          else { hi = best = x; fh = x.over; if (last > 0) fl /= 2; last = 1; }
        }
        at(best.cut);
        ff(["-i", tmp2, "-af", `volume=${(-1 - best.q.truePeak).toFixed(2)}dB`, "-c:a", "pcm_s16le", path.join(KIT, rel)]);
        m = loudness(path.join(KIT, rel));
      }
      files.push({ file: rel, momentary: m.momentary, lufs: m.lufs, phone: m.phone, truePeak: m.truePeak, length: +len.toFixed(3) });
      console.log(`${rel.padEnd(16)} ${len.toFixed(2)} s  momentary ${m.momentary}  ${m.lufs} LUFS  crest ${(m.truePeak - m.momentary).toFixed(1)} (cap ${cap})  phone ${m.phone}`);
    }
    out.candidates[key] = { note: cand.note, files };
  }
  manifest.slots[name] = out;
}
for (const t of ["tmp.wav", "tmp2.wav"]) fs.rmSync(path.join(CACHE, t), { force: true });
fs.writeFileSync(path.join(KIT, "manifest.json"), JSON.stringify(manifest, null, 1) + "\n");
console.log(`\nkit written to ${path.relative(process.cwd(), KIT)} (sound ${manifest.enabled ? "enabled" : "on hold"})`);
